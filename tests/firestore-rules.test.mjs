import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const env = await initializeTestEnvironment({ projectId: 'demo-rise', firestore: { rules: readFileSync(fileURLToPath(new URL('../firestore.rules', import.meta.url)), 'utf8'), host: '127.0.0.1', port: 8089 } });
const as = (uid, email) => env.authenticatedContext(uid, { email }).firestore();
const anon = env.unauthenticatedContext().firestore();
let pass = 0, fail = 0;
const t = async (name, p, expect) => { try { await (expect ? assertSucceeds(p) : assertFails(p)); pass++; } catch (e) { fail++; console.log('FAIL', name, e.message.split('\n')[0]); } };
const reset = () => env.withSecurityRulesDisabled(async c => { const d = c.firestore();
  await d.doc('familyLinks/G_C').set({ guardianUid: 'G', childUid: 'C', status: 'active' });
  await d.doc('users/C/sync/familySummary').set({ x: 1 });
  await d.doc('users/C/assignments/a1').set({ createdBy: 'G', childUid: 'C', status: 'pending', subject: 'Maths' });
  await d.doc('users/C/assignments/a2').set({ createdBy: 'G', childUid: 'C', status: 'completed', subject: 'Maths', attempts: [] });
  await d.doc('challenges/ABC123').set({ code: 'ABC123', questionIds: [1], results: [{ score: 1 }] });
});
await reset();
const C = as('C', 'c@x.com'), G = as('G', 'g@x.com'), X = as('X', 'x@x.com');
await t('owner writes own sync', C.doc('users/C/sync/progress').set({ data: {} }), true);
await t('other user reads sync', X.doc('users/C/sync/progress').get(), false);
await t('linked guardian reads summary', G.doc('users/C/sync/familySummary').get(), true);
await t('stranger reads summary', X.doc('users/C/sync/familySummary').get(), false);
await t('guardian creates with link', G.collection('users/C/assignments').add({ createdBy: 'G', childUid: 'C', status: 'pending' }), true);
await t('stranger creates', X.collection('users/C/assignments').add({ createdBy: 'X', childUid: 'C', status: 'pending' }), false);
await t('guardian spoofs createdBy', G.collection('users/C/assignments').add({ createdBy: 'Z', childUid: 'C', status: 'pending' }), false);
await t('child creates own assignment', C.collection('users/C/assignments').add({ createdBy: 'C', childUid: 'C', status: 'pending' }), false);
await t('child reads own list', C.collection('users/C/assignments').get(), true);
await t('guardian reads filtered list', G.collection('users/C/assignments').where('createdBy', '==', 'G').get(), true);
await t('child submits result', C.doc('users/C/assignments/a1').update({ status: 'completed', attempts: [{ score: 3 }], result: { score: 3 }, lastSubmittedAt: 1 }), true);
await reset();
await t('child changes subject', C.doc('users/C/assignments/a1').update({ status: 'completed', subject: 'Easy' }), false);
await t('child cancels', C.doc('users/C/assignments/a1').update({ status: 'cancelled' }), false);
await t('child re-attempts completed', C.doc('users/C/assignments/a2').update({ status: 'completed', attempts: [{ score: 1 }, { score: 2 }], lastSubmittedAt: 2 }), true);
await t('guardian cancels pending', G.doc('users/C/assignments/a1').update({ status: 'cancelled', cancelledAt: 1 }), true);
await t('guardian cancels completed', G.doc('users/C/assignments/a2').update({ status: 'cancelled', cancelledAt: 1 }), false);
await t('guardian edits score', G.doc('users/C/assignments/a2').update({ attempts: [{ score: 99 }] }), false);
await t('anyone deletes', G.doc('users/C/assignments/a2').delete(), false);
await t('party reads link', C.doc('familyLinks/G_C').get(), true);
await t('stranger reads link', X.doc('familyLinks/G_C').get(), false);
await t('guest opens challenge', anon.doc('challenges/ABC123').get(), true);
await t('player appends result', X.doc('challenges/ABC123').update({ results: [{ score: 1 }, { score: 5 }] }), true);
await t('player rewrites questions', X.doc('challenges/ABC123').update({ questionIds: [9] }), false);
await t('player wipes results', X.doc('challenges/ABC123').update({ results: [] }), false);
await t('room update', anon.doc('rooms/R1').set({ state: 'lobby' }), true);
console.log(`passed ${pass}, failed ${fail}`);
await env.cleanup();
process.exit(fail ? 1 : 0);
