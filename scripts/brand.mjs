#!/usr/bin/env node
// Propagates the Brand block of public/design-config.css to files CSS can't reach:
// <meta name="theme-color">, manifest.json, favicon.svg, og-image.svg/.png and PWA icons.
//   node scripts/brand.mjs          rewrite files and re-render PNGs (needs Playwright)
//   node scripts/brand.mjs --check  exit 1 if anything is out of sync (CI, no Playwright)
//   node scripts/brand.mjs --preset original   apply a named palette from brand-presets.json first
//   node scripts/brand.mjs --list   show available presets
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = join(ROOT, 'public');
const LOCK = join(ROOT, 'scripts', 'brand-lock.json');
const CHECK = process.argv.includes('--check');
const read = rel => readFileSync(join(PUBLIC, rel), 'utf8');

function tokens() {
  const css = read('design-config.css');
  const raw = {};
  for (const [, name, value] of css.matchAll(/--([\w-]+):\s*([^;]+);/g)) raw[name] = value.trim();
  const resolve = (name, seen = new Set()) => {
    const v = raw[name];
    if (v === undefined || seen.has(name)) throw new Error(`design-config.css: cannot resolve --${name}`);
    const ref = v.match(/^var\(--([\w-]+)\)$/);
    if (ref) return resolve(ref[1], seen.add(name));
    if (!/^#[0-9a-fA-F]{6}$/.test(v)) throw new Error(`design-config.css: --${name} must be a #rrggbb hex, got "${v}"`);
    return v.toLowerCase();
  };
  const t = {};
  for (const n of ['primary', 'primary-dark', 'brand-logo', 'brand-grad-start', 'brand-grad-mid', 'brand-grad-end']) t[n] = resolve(n);
  return t;
}

const GLYPH = `<rect x="5"  y="22" width="5" height="5"  rx="1.5" fill="rgba(255,255,255,0.55)"/>
  <rect x="13" y="17" width="5" height="10" rx="1.5" fill="rgba(255,255,255,0.78)"/>
  <rect x="21" y="11" width="5" height="16" rx="1.5" fill="#ffffff"/>
  <polygon points="23.5,4 27,9.5 20,9.5" fill="#ffffff"/>`;

const favicon = t => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <!-- Generated by scripts/brand.mjs from design-config.css (--brand-logo). Do not edit. -->
  <rect width="32" height="32" rx="7" fill="${t['brand-logo']}"/>
  ${GLYPH}
</svg>
`;
const maskable = t => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <rect width="32" height="32" fill="${t['brand-logo']}"/>
  <g transform="translate(3.2 3.2) scale(0.8)">${GLYPH}</g>
</svg>`;

function textFiles(t) {
  const out = {};
  out['favicon.svg'] = favicon(t);
  out['index.html'] = read('index.html').replace(/(<meta name="theme-color" content=")#[0-9a-fA-F]{6}(">)/, `$1${t.primary}$2`);
  out['manifest.json'] = read('manifest.json').replace(/("theme_color":\s*")#[0-9a-fA-F]{6}(")/, `$1${t.primary}$2`);
  const stops = [t['brand-grad-start'], t['brand-grad-mid'], t['brand-grad-end']];
  let i = 0;
  out['og-image.svg'] = read('og-image.svg')
    .replace(/(<linearGradient id="brand"[\s\S]*?<\/linearGradient>)/, g => g.replace(/stop-color="#[0-9a-fA-F]{6}"/g, () => `stop-color="${stops[i++]}"`))
    .replace(/flood-color="#[0-9a-fA-F]{6}"/, `flood-color="${t['primary-dark']}"`);
  return out;
}

const ogHash = () => createHash('sha256').update(readFileSync(join(PUBLIC, 'og-image.png'))).digest('hex').slice(0, 8);
const stampOg = html => html.replace(/og-image\.png\?v=\w+/g, `og-image.png?v=${ogHash()}`);

const PRESETS = JSON.parse(readFileSync(join(ROOT, 'scripts', 'brand-presets.json'), 'utf8'));
if (process.argv.includes('--list')) {
  for (const [name, p] of Object.entries(PRESETS)) console.log(`${name.padEnd(10)} ${p.description}`);
  process.exit(0);
}
const presetArg = process.argv[process.argv.indexOf('--preset') + 1];
if (process.argv.includes('--preset')) {
  const preset = PRESETS[presetArg];
  if (!preset) { console.error(`Unknown preset "${presetArg}". Available: ${Object.keys(PRESETS).join(', ')}`); process.exit(1); }
  const path = join(PUBLIC, 'design-config.css');
  let css = readFileSync(path, 'utf8');
  for (const [name, value] of Object.entries(preset.tokens)) {
    const re = new RegExp(`(--${name}:\\s*)[^;]+;`);
    if (!re.test(css)) { console.error(`design-config.css has no --${name}`); process.exit(1); }
    css = css.replace(re, `$1${value};`);
  }
  writeFileSync(path, css);
  console.log(`Applied preset "${presetArg}" to design-config.css`);
}

const t = tokens();
const files = textFiles(t);
const problems = [];

if (CHECK) {
  for (const [rel, want] of Object.entries(files)) {
    const have = read(rel);
    const cmp = rel === 'index.html' ? stampOg(want) : want;
    if (have !== cmp) problems.push(`${rel} is out of sync with design-config.css`);
  }
  let lock = {};
  try { lock = JSON.parse(readFileSync(LOCK, 'utf8')); } catch {}
  if (JSON.stringify(lock.tokens) !== JSON.stringify(t)) problems.push('PNG icons / og-image.png were rendered from different brand colours');
  if (problems.length) {
    console.error(problems.join('\n') + '\n\nBrand out of sync — run: npm run brand');
    process.exit(1);
  }
  console.log('Brand assets in sync.');
} else {
  for (const [rel, content] of Object.entries(files)) if (rel !== 'index.html') writeFileSync(join(PUBLIC, rel), content);
  const { chromium } = createRequire(import.meta.url)('playwright');
  const browser = await chromium.launch();
  const render = async (svg, w, h, out) => {
    const page = await browser.newPage({ viewport: { width: w, height: h } });
    await page.setContent(`<html><body style="margin:0;background:transparent">${svg.replace('<svg ', `<svg width="${w}" height="${h}" `)}</body></html>`);
    await page.screenshot({ path: join(PUBLIC, out), omitBackground: true });
    await page.close();
  };
  for (const s of [192, 512]) {
    await render(favicon(t), s, s, `icons/icon-${s}.png`);
    await render(maskable(t), s, s, `icons/icon-maskable-${s}.png`);
  }
  await render(read('og-image.svg').replace(/ width="1200" height="630"/, ''), 1200, 630, 'og-image.png');
  await browser.close();
  writeFileSync(join(PUBLIC, 'index.html'), stampOg(files['index.html']));
  writeFileSync(LOCK, JSON.stringify({ tokens: t }, null, 2) + '\n');
  console.log('Brand assets written:', Object.values(t).join(' '));
}
